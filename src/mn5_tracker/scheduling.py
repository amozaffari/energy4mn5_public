"""Daily `mn5track sync` on the user's machine: a macOS launchd agent, or a Hermes Agent cron
script. Never cron on MN5."""

import os
import plistlib
import shlex
import shutil
import subprocess
from pathlib import Path

from mn5_tracker.config import CONFIG_ENV_VAR, DB_ENV_VAR, REPO_ROOT, find_db_path


LABEL = "com.mn5track.sync"
PLIST_PATH = Path.home() / "Library" / "LaunchAgents" / f"{LABEL}.plist"
LOG_PATH = Path.home() / "Library" / "Logs" / "mn5track.log"
HERMES_SCRIPT_NAME = "mn5track-daily.sh"


def sync_script() -> str:
    """Sync, refresh the dashboards, then alerts; a notification fires when alerts are raised."""
    uv = shlex.quote(shutil.which("uv") or "uv")
    project = shlex.quote(str(REPO_ROOT))
    run = f"{uv} run --project {project} mn5track"
    notify = (
        'osascript -e \'display notification "Run mn5track alerts for details" '
        'with title "MN5 compute tracker"\''
    )

    return f"date; {run} sync; {run} dashboard --all; {run} alerts || {notify}"


def render_plist(hour: int) -> str:
    plist = {
        "Label": LABEL,
        "ProgramArguments": ["/bin/zsh", "-lc", sync_script()],
        "StartCalendarInterval": {"Hour": hour, "Minute": 0},
        # launchd skips runs while the Mac sleeps; RunAtLoad catches up after a reboot or login.
        "RunAtLoad": True,
        "StandardOutPath": str(LOG_PATH),
        "StandardErrorPath": str(LOG_PATH),
        "WorkingDirectory": str(REPO_ROOT),
    }

    return plistlib.dumps(plist).decode()


def launchd_domain() -> str:
    return f"gui/{os.getuid()}"


def install(hour: int) -> Path:
    PLIST_PATH.parent.mkdir(parents=True, exist_ok=True)
    LOG_PATH.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["launchctl", "bootout", launchd_domain(), str(PLIST_PATH)], check=False)
    PLIST_PATH.write_text(render_plist(hour))
    subprocess.run(["launchctl", "bootstrap", launchd_domain(), str(PLIST_PATH)], check=True)

    return PLIST_PATH


def uninstall() -> None:
    subprocess.run(["launchctl", "bootout", launchd_domain(), str(PLIST_PATH)], check=False)
    PLIST_PATH.unlink(missing_ok=True)


def hermes_home() -> Path:
    return Path(os.environ.get("HERMES_HOME", Path.home() / ".hermes")).expanduser()


def hermes_script() -> str:
    """Hermes delivers a script's stdout and alerts on a non-zero exit, so the script is silent
    when all is well, prints the alerts when there are any, and fails only when sync fails."""
    uv = shlex.quote(shutil.which("uv") or "uv")
    project = shlex.quote(str(REPO_ROOT))
    log = shlex.quote(str(find_db_path().parent / "daily.log"))
    run = f"{uv} run --project {project} mn5track"

    # Cron runs without the user's shell, so config and database overrides are carried over.
    exports = [
        f"export {name}={shlex.quote(os.environ[name])}"
        for name in (CONFIG_ENV_VAR, DB_ENV_VAR)
        if os.environ.get(name)
    ]

    return "\n".join(
        [
            "#!/usr/bin/env bash",
            "# Generated by `mn5track schedule hermes`; regenerate instead of editing.",
            "set -uo pipefail",
            *exports,
            f"cd {project}",
            f"{{ date; {run} sync && {run} dashboard --all; }} >> {log} 2>&1 || {{",
            '  echo "MN5 compute tracker: daily sync failed. Last log lines:"',
            f"  tail -n 20 {log}",
            "  exit 1",
            "}",
            f"{run} alerts --message",
            "",
        ]
    )


def install_hermes_script() -> Path:
    path = hermes_home() / "scripts" / HERMES_SCRIPT_NAME
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(hermes_script())
    path.chmod(0o755)

    return path


def hermes_cron_command(hour: int, deliver: str) -> str:
    return (
        f'hermes cron create "0 {hour} * * *" --no-agent --script {HERMES_SCRIPT_NAME} '
        f"--deliver {shlex.quote(deliver)} --name mn5track-daily"
    )
